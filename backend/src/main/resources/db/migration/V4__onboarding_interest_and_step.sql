-- V4: 온보딩 관심사 계층 · 우선순위 · 진행 단계 (BMA-38)
--
-- S2 사양서 v1.4 가 기존 스키마로 표현할 수 없는 세 가지를 요구한다.
--
-- 1) 관심사 대분류 -> 세부 2단계 구조 (S2-10, S2-11)
--    "문화생활" 아래 "영화·전시/미술관·공연/뮤지컬·콘서트·독서" 처럼 계층이 있다.
--    ON_QUESTION_OPTION 은 평면 구조라 부모-자식 관계를 담을 수 없었다.
--
-- 2) 관심사 우선순위 (S2-13)
--    "더 마음이 가는 순서대로 끌어서 정렬" 하고 1순위 배지를 붙인다.
--    ON_USER_ANSWER 에 순서를 담을 컬럼이 없었다. ANSWER_NUMBER 는 척도 문항용
--    이라 의미가 다르므로 전용하지 않는다. 이 값은 매칭 스코어링에 쓰인다.
--
-- 3) 진행률 7구간 (S2-01, S2-02)
--    "N/7" 은 문항 22개가 아니라 그룹 순번 기준이다. 관심사가 1구간이고
--    나머지 18문항이 6구간에 분산된다. 어느 문항이 몇 번째 구간인지 담을 곳이
--    없어 프론트가 하드코딩해야 했다. 문항이 바뀔 때마다 프론트를 고쳐야 하므로
--    데이터로 내려준다.
--
-- 실제 질문·보기 콘텐츠는 아직 미확정이라 구조만 만든다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 보기 계층: 세부 관심사는 대분류 보기를 부모로 갖는다.
--    일반 문항의 보기는 부모가 없어 NULL 이다.
-- ---------------------------------------------------------------------
ALTER TABLE `ON_QUESTION_OPTION`
    ADD COLUMN `PARENT_OPTION_ID` BIGINT UNSIGNED NULL
        COMMENT '상위 보기 ID. 세부 관심사가 대분류를 가리킨다. 일반 보기는 NULL'
        AFTER `QUESTION_ID`,
    ADD INDEX `IX_ON_OPTION_PARENT` (`PARENT_OPTION_ID`, `SORT_ORDER`),
    -- 자기 자신을 부모로 두거나 순환하는 것은 애플리케이션에서 막는다.
    -- (MySQL 은 재귀 제약을 걸 수 없다)
    ADD CONSTRAINT `FK_ON_OPTION_PARENT` FOREIGN KEY (`PARENT_OPTION_ID`)
        REFERENCES `ON_QUESTION_OPTION` (`OPTION_ID`) ON DELETE RESTRICT ON UPDATE CASCADE;

-- ---------------------------------------------------------------------
-- 2) 답변 우선순위: 1 부터 시작하는 순번. 순서가 없는 답변은 NULL.
-- ---------------------------------------------------------------------
ALTER TABLE `ON_USER_ANSWER`
    ADD COLUMN `ANSWER_RANK` INT UNSIGNED NULL
        COMMENT '사용자가 매긴 우선순위(1이 가장 높음). 순서 개념이 없는 답변은 NULL'
        AFTER `ANSWER_NUMBER`;

-- ---------------------------------------------------------------------
-- 3) 진행 단계: 화면에 N/7 로 표시할 구간 번호.
--    같은 STEP_NO 를 가진 문항들이 한 화면(또는 한 구간)에 묶인다.
--    기본값 0 은 "미배정" 이다. 콘텐츠 확정 시 1~7 을 채운다.
-- ---------------------------------------------------------------------
ALTER TABLE `ON_QUESTION`
    ADD COLUMN `STEP_NO` INT NOT NULL DEFAULT 0
        COMMENT '진행률 표시용 구간 번호(1부터). 0 은 미배정'
        AFTER `SORT_ORDER`,
    ADD INDEX `IX_ON_QUESTION_STEP` (`STEP_NO`, `SORT_ORDER`);
